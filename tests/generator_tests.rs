use axotyped::{
    AuthScheme, GeneratorConfig, HttpMethod, RouteCollection, RouteDefinition, api_routes,
    generate, generate_with_warnings,
};

fn yauth_config() -> GeneratorConfig {
    GeneratorConfig {
        bindings_dir: "./bindings".into(),
        output_path: "./packages/client/src/generated.ts".into(),
        factory_name: "createYAuthClient".into(),
        enable_groups: true,
        error_class_name: "YAuthError".into(),
        options_interface_name: "YAuthClientOptions".into(),
        default_credentials: "include".into(),
        type_import_prefix: "../../../../bindings".into(),
        format_command: None,
        ws_ticket_path: None,
        large_int_type: "number".into(),
        auth_scheme: AuthScheme::Bearer,
        csrf_header_name: None,
    }
}

fn sample_routes() -> axotyped::RouteCollection {
    let mut routes = api_routes! {
        getSession: GET "/session" [auth]
            -> SessionResponse;
        logout: POST "/logout" [auth]
            -> SuccessResponse;
        updateProfile: PATCH "/me" [auth]
            body: UpdateProfileRequest -> ProfileResponse;
    };

    let ep = api_routes! {
        @group emailPassword

        register: POST "/register"
            body: RegisterRequest -> MessageResponse;
        login: POST "/login"
            body: LoginRequest -> LoginResponse;
        verify: POST "/verify-email"
            body: VerifyEmailRequest -> MessageResponse;
        changePassword: POST "/change-password" [auth]
            body: ChangePasswordRequest -> MessageResponse;
    };
    routes.extend(ep);

    let admin = api_routes! {
        @group admin

        listUsers: GET "/admin/users" [auth]
            query: ListUsersQuery -> ListUsersResponse;
        getUser: GET "/admin/users/{id}" [auth]
            -> UserResponse;
        deleteUser: DELETE "/admin/users/{id}" [auth];
        banUser: POST "/admin/users/{id}/ban" [auth]
            body: BanRequest -> UserResponse;
    };
    routes.extend(admin);

    let oauth = api_routes! {
        @group oauth

        authorize: GET "/oauth/{provider}/authorize" [redirect]
            query: AuthorizeQuery;
        callback: POST "/oauth/{provider}/callback"
            body: CallbackBody -> AuthResponse;
    };
    routes.extend(oauth);

    let ws = api_routes! {
        @group realtime

        wsUpgrade: GET "/ws" [ws]
            send: ClientEvent, receive: ServerEvent
            query: WsParams;
    };
    routes.extend(ws);

    routes
}

#[test]
fn generic_types_generate_separate_imports() {
    // ContentResponse<Dialog> should import ContentResponse and Dialog separately,
    // not produce a broken "ContentResponse<Dialog>" import with <> in the path.
    let routes = api_routes! {
        getDialogs: GET "/dialogs"
            -> ContentResponse<Dialog>;
    };
    let config = GeneratorConfig {
        enable_groups: false,
        ..Default::default()
    };
    let output = generate(&routes, &config);

    // Should import each type separately
    assert!(
        output.contains("import type { ContentResponse }"),
        "should import ContentResponse separately, got:\n{}",
        output
    );
    assert!(
        output.contains("import type { Dialog }"),
        "should import Dialog separately, got:\n{}",
        output
    );

    // Should NOT contain angle brackets in import paths
    assert!(
        !output.contains("from \"./ContentResponse<Dialog>\""),
        "import path should not contain angle brackets, got:\n{}",
        output
    );
    assert!(
        !output.contains("import type { ContentResponse<Dialog> }"),
        "import should not contain angle brackets in the type name, got:\n{}",
        output
    );
}

