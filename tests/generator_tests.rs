#[test]
#[should_panic(expected = "duplicate method name")]
fn flat_layout_duplicate_method_names_fail_generation() {
    // build() only rejects duplicates within one group; the flat layout
    // puts every method at the top level, where a duplicate key is invalid
    // (TS1117) or silently shadows the first endpoint. Same name in
    // different groups stays fine — see same_name_in_different_groups_is_fine.
    let mut routes = RouteCollection::new();
    routes.push(manual_route(
        "listUsers",
        "/v1/users",
        axotyped::Visibility::Private,
        axotyped::Visibility::Private,
    ));
    routes.push(manual_route(
        "listUsers",
        "/v2/users",
        axotyped::Visibility::Private,
        axotyped::Visibility::Private,
    ));
    let config = GeneratorConfig {
        enable_groups: false,
        ..Default::default()
    };
    let _ = generate(&routes, &config);
}

#[test]
fn check_detects_out_of_sync() {
    use std::io::Write;

    let routes = sample_routes();
    let dir = std::env::temp_dir().join("axotyped_test");
    std::fs::create_dir_all(&dir).unwrap();
    let output_path = dir.join("generated.ts");

    let config = GeneratorConfig {
        output_path: output_path.to_string_lossy().into(),
        ..yauth_config()
    };

    // Write wrong content
    let mut f = std::fs::File::create(&output_path).unwrap();
    writeln!(f, "// old content").unwrap();
    drop(f);

    // Check should fail
    let result = axotyped::check(&routes, &config);
    assert!(result.is_err());

    // Now write correct content
    axotyped::generate_to_file(&routes, &config).unwrap();

    // Check should pass
    let result = axotyped::check(&routes, &config);
    assert!(result.is_ok());

    // Cleanup
    std::fs::remove_dir_all(&dir).ok();
}

